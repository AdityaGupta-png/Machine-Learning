
# Indexing --> Access the values from the Index 

name = "Aditya"
print(name[0])
print(name[4])
print(name[5])


# Slcing --> slice the index and print the value 
#  [first_index : last_index] --> first index is include
# last_index --> last index is not include

clg = "Universal"
print(clg[0: 5])
print(clg[0: 6: 2])

# Python also consits the negative indexing 
clg = "Banaras"
print(clg[-1])
print(clg[-1: -5: -1])