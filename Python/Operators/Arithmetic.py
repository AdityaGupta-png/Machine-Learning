#  Performing operation on the operators 

# Addition operation 
a = 10
b = 20
print(a + b)

# Substraction operation 
a = 33.55
b = 22.11
print(a - b)

# Multiplication operator 
a = 21.222
b = 32.333
print(a * b)

# Division operator
a = 55.222
b = 88.111
print(a / b)

# Modulo operator 
a = 44.5555
b = 77.2222
print(a % b)

# floor dividon --> result converted into integer 
a = 33
b = 55
print(a // b)

# Power operator 
a = 22
b = 44
print(a ** b)
